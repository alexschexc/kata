"""Generate rust/crates/kata-core/src/book_catalog.rs from src/book_catalog.zig.

The Zig file is itself generated from the installed sources by tests/discover_books.py; this
keeps the Rust table byte-for-byte equivalent. Usage: python3 -I scripts/generate-rust-catalog.py
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'src/book_catalog.zig').read_text()


def option(text):
    text = text.strip()
    return 'None' if text == 'null' else 'Some(%s)' % text


def option_list(body):
    return '[%s]' % ', '.join(option(part) for part in re.findall(r'"[^"]*"|null', body))


entries = []
for line in source.splitlines():
    if not line.strip().startswith('.{ .name'):
        continue
    name = re.search(r'\.name = ("[^"]*")', line).group(1)
    chapters = re.search(r'\.chapters = \.\{ ([^}]*) \}', line).group(1)
    query = re.search(r'\.query_names = \.\{ ([^}]*) \}', line).group(1)
    aliases = re.search(r'\.aliases = \.\{ ([^}]*) \}', line).group(1)
    present_body = re.search(r'\.present_chapters = \.\{ (.*) \} \},?$', line).group(1)
    present = re.findall(r'&\.\{([^}]*)\}', present_body)
    assert len(present) == 3, line
    lists = ['&[%s]' % ', '.join(n.strip() for n in p.split(',') if n.strip()) for p in present]
    entries.append('    Entry {\n        name: %s,\n        chapters: [%s],\n        query_names: %s,\n'
                   '        aliases: %s,\n        present_chapters: [%s],\n    },'
                   % (name, chapters, option_list(query), option_list(aliases), ', '.join(lists)))

out = ['// Generated by scripts/generate-rust-catalog.py from src/book_catalog.zig. Do not edit.',
       '',
       '/// One book across the three bundled sources (index 0 kjv, 1 grb, 2 vul).',
       '#[derive(Debug)]',
       'pub struct Entry {',
       '    pub name: &\'static str,',
       '    /// Highest chapter per source; 0 means the source lacks the book.',
       '    pub chapters: [u16; 3],',
       '    /// The source\'s own spelling of the book name.',
       '    pub query_names: [Option<&\'static str>; 3],',
       '    pub aliases: [Option<&\'static str>; 3],',
       '    /// Chapters actually present in each source (sources have gaps).',
       '    pub present_chapters: [&\'static [u16]; 3],',
       '}',
       '',
       'pub static CATALOG: [Entry; %d] = [' % len(entries)] + entries + ['];', '']
(ROOT / 'rust/crates/kata-core/src/book_catalog.rs').write_text('\n'.join(out))
print('wrote', len(entries), 'entries')
